"""Generate docs/demo_script.md. Every number is read from results/*.csv (or computed from them) at build time.

The one local-only input is data/judge/method_membership.csv (gitignored, unblinded after the judge step): it says which
method produced each judged paper, so BM25 shares and the V4/BM25 overlap are computed from it plus results/judgments.csv.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app import data  # noqa: E402

GWT, PP, CH, IIT, PAN = ("global_workspace", "predictive_processing_fep", "champagne_semiotic",
                         "integrated_information", "panpsychism")


def pct(x: float) -> str:
    return f"{round(100 * x)}%"


def auc(s: pd.Series, m: str, per: str) -> str:
    return f"{s[f'{m}_cand_auc_{per}']} [{s[f'{m}_cand_auc_{per}_ci_lo']}, {s[f'{m}_cand_auc_{per}_ci_hi']}]"


def method_shares() -> dict:
    """R share of the top 30 per method for GWT and PP, and the number of papers on both lists."""
    mem = pd.read_csv(ROOT / "data/judge/method_membership.csv", dtype=str)
    mem = mem[mem.is_repeat == "0"]
    j = pd.read_csv(ROOT / "results/judgments.csv", dtype=str)
    j = j[j.item_id.isin(mem.item_id)].drop_duplicates("item_id")
    mem = mem.merge(j[["item_id", "verdict"]], on="item_id")
    out = {}
    for th in (GWT, PP):
        t = mem[mem.theory == th]
        for meth in ("V4", "BM25"):
            sub = t[t.methods.str.contains(meth)]
            out[(th, meth)] = (int((sub.verdict == "R").sum()), len(sub))
        out[(th, "both")] = int((t.methods == "BM25+V4").sum())
    return out


def window_stability(t: pd.DataFrame, th: str) -> tuple[int, int]:
    a = set(t[(t.theory == th) & (t.window == "1995-2015")].pmcid)
    b = t[(t.theory == th) & (t.window == "1995-2025")]
    return len(a & set(b.pmcid)), int((b.year > 2015).sum())


def build() -> str:
    d = data.load_all()
    s = d["summary_metrics.csv"].set_index("theory")
    t = d["level3_top.csv"]
    ms = method_shares()
    readme = (ROOT / "results/README.md").read_text()
    kappa = re.search(r"kappa (0\.\d+)", readme).group(1)
    g, p, c, i, a = (s.loc[x] for x in (GWT, PP, CH, IIT, PAN))
    ex = t[(t.theory == GWT) & (t.window == "1995-2015") & (t.judge_verdict == "R")].head(2)
    gc, cc = data.judge_counts(GWT, "1995-2015", d), data.judge_counts(CH, "1995-2015", d)
    shares = lambda th, m: f"{ms[(th, m)][0]} of {ms[(th, m)][1]} ({pct(ms[(th, m)][0] / ms[(th, m)][1])})"
    disc = d["discriminability.csv"]
    off = disc[(disc.period == "1995-2015") & (disc.pool == "candidate_pool_only") & (disc.is_diagonal == "false")]
    off = off.assign(v=off.mean_percentile_rank.astype(float)).sort_values("v", ascending=False).head(3)
    conf = "; ".join(f"{data.THEORIES[r.row_profile]} profile on {data.THEORIES[r.column_positives]} papers "
                     f"({r.v:.0f})" for r in off.itertuples())
    stab = {th: window_stability(t, th) for th in (GWT, CH)}
    ex_txt = "\n".join(f"   - *\"{r.title}\"* ({r.year}); parallels claim `{r.best_claim_id}`. Judge: {r.judge_reason}"
                       for r in ex.itertuples())
    trend = d["window_trends.csv"]
    return f"""# Demo script (about 4 minutes)

Generated by `app/build_demo.py`; every number is read from `results/` at build time (not typed by hand). Re-run the
script if the results change. Spoken text is in plain paragraphs; **[bracketed bold]** lines are what to do on screen.

## 1. The problem and the idea (0:00-0:30)
Theories of consciousness each have their own literature, and it is scattered across journals and fields. Keyword search
finds the papers that use a theory's name. It misses papers that discuss the same ideas without the name. This tool finds
both, at three levels: the references on each Landscape of Consciousness page, the papers that name the theory, and papers
that are conceptually close to the theory but never name it. That third level is the point of the project.

## 2. Three levels, live, with Global Workspace Theory (0:30-1:50)
**[Pick Global Workspace Theory, window 1995-2015.]**
- *References.* The LoC page lists {g.loc_references} references; {g.loc_fulltext_seeds_any_oa_route} have free full text.
  Many entries are books or videos. **[Tab 1]**
- *Direct mentions.* {g.silver_exclusive_1995_2015_corpus} papers in the 1995-2015 corpus name GWT and no other theory.
  The chart uses full Europe PMC counts: {g.rate_per_10k_1995_2015} papers per 10,000 open-access papers in 1995-2015,
  {g.rate_per_10k_2016_2025} in 2016-2025. **[Tab 2, point at the chart]**
- *Conceptual associations.* These papers never name the theory. **[Tab 3]** The LLM judge rated
  {gc['R']} of the top {gc['judged']} as conceptual neighbors. Two examples:
{ex_txt}

Say it plainly: the judge is an LLM, blind to the ranking, and I checked it against my own labels on a sample
(agreement was moderate, kappa {kappa}). It is evidence, not ground truth.

## 3. A sparse theory: Champagne's semiotic account (1:50-2:20)
**[Pick Champagne.]** Only {c.silver_exclusive_1995_2015_corpus} papers in the 1995-2015 corpus name it, so everything
is marked exploratory. The judge rated {cc['R']} of {cc['judged']} top papers as neighbors and {cc['G']} as generic
consciousness papers. Open-access biomedical literature barely covers this philosophy, so I report that instead of
hiding it. Panpsychism is similar ({a.silver_exclusive_1995_2015_corpus} papers).

## 4. The window selector (2:20-2:50)
**[Switch to 1995-2025.]** The top 30 changes as later papers enter. For GWT, {stab[GWT][0]} of the 30 papers from the 1995-2015
list are still in the 1995-2025 list, and {stab[GWT][1]} of the 30 are from after 2015. For Champagne the numbers are
{stab[CH][0]} and {stab[CH][1]}. This is descriptive: **papers after 2015 are not judged**, and the 2016-2025 lists
are capped samples.

## 5. How I checked it (2:50-3:40)
- *Term-masked test.* I blank out the theory's names in papers that name it, then ask whether the method still ranks
  them above other papers. Candidate-only AUC (0.5 is chance), 1995-2015 then 2016-2025:
  GWT {auc(g, 'V4', '1995_2015')} vs keyword ranking (BM25) {auc(g, 'BM25', '1995_2015')};
  later {auc(g, 'V4', '2016_2025')} vs {auc(g, 'BM25', '2016_2025')}.
- *Conceptual and keyword search find almost entirely different papers.* Top-30 lists share {ms[(GWT, 'both')]} paper for GWT
  and {ms[(PP, 'both')]} for predictive processing.
- *Judge, GWT.* {shares(GWT, 'V4')} judged relevant for the conceptual method versus {shares(GWT, 'BM25')} for keyword
  ranking. That lead is clear only at the top 30; at the top 10 and top 20 the confidence intervals include zero
  (`reports/level3_judge.md`).
- *Predictive processing is a tie or a keyword win.* Judge: {shares(PP, 'V4')} versus {shares(PP, 'BM25')}. Candidate-only AUC:
  1995-2015 {auc(p, 'V4', '1995_2015')} vs BM25 {auc(p, 'BM25', '1995_2015')}; 2016-2025 BM25 is ahead,
  {auc(p, 'BM25', '2016_2025')} vs {auc(p, 'V4', '2016_2025')}.
- *Out-of-time.* Candidate-only AUC fell for every theory between 1995-2015 and 2016-2025: Champagne
  {c.V4_cand_auc_1995_2015} to {c.V4_cand_auc_2016_2025}, GWT {g.V4_cand_auc_1995_2015} to {g.V4_cand_auc_2016_2025},
  IIT {i.V4_cand_auc_1995_2015} to {i.V4_cand_auc_2016_2025}, panpsychism {a.V4_cand_auc_1995_2015} to
  {a.V4_cand_auc_2016_2025}, predictive processing {p.V4_cand_auc_1995_2015} to {p.V4_cand_auc_2016_2025}. All stay above 0.5.
  The small-theory drops may be partly regression from tiny 1995-2015 samples (n = {c.cand_auc_1995_2015_n_positives},
  {i.cand_auc_1995_2015_n_positives}, {a.cand_auc_1995_2015_n_positives} for Champagne, IIT, panpsychism); I did not test that,
  and the keyword baseline also fell for some theories.
- *Theory profiles.* Each theory's profile finds its own papers best, but Champagne, IIT and panpsychism are the most confusable
  group (1995-2015, candidate pool, mean percentile: {conf}).
- *What did not work.* The contrast variant (V5), meant to reduce generic-consciousness drift, failed GWT against all negatives, and
  the pre-registered rule selected the simpler V4. V5 looked better on predictive processing in the 1995-2015 test, but I did not switch
  after seeing that. Predictive processing is also where plain keywords hold up (above).

## 6. Limits and what comes next (3:40-4:00)
Open access only: philosophy books and paywalled journals are missing, which is why the sparse theories are thin. All
negatives are unlabeled, so scores are lower bounds. Next: a second source such as CORE for philosophy coverage, and
judging the later-window papers.

## Likely questions, honest answers
- **Why not just search the term?** You should, for papers that name the theory; that is Level 2. Level 3 targets the
  papers that never name it. In my tests the two methods return almost entirely different papers (above), and the
  keyword baseline is as good or better for predictive processing.
- **Why is LLM judging not ground truth?** The judge saw abstracts and two passages, not full texts, and shares LLM biases.
  Agreement with my labels was moderate (kappa {kappa}). I use it to filter generic papers and explain parallels.
- **What do the numbers not show?** They do not show that the neighbors are *correct* neighbors, only that masked
  theory papers rank above other papers and that a judge found many of the top picks relevant. Negatives are unlabeled,
  positives are single-theory papers, and the candidate-pool confound means the candidate-only AUC is the one to read.
  Small theories (n < 20) are exploratory. The 2016-2025 test shows generalization, not forecasting: the profiles use current LoC text.
- **Did the 2016-2025 lists get judged?** No. They are marked "not judged".
- **Is the 2016-2025 list complete?** No. It is a capped sample; totals come from the full counts in the chart.
"""


if __name__ == "__main__":
    out = ROOT / "docs" / "demo_script.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(build())
    print(out)
